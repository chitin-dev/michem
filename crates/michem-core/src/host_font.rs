//! Typst measures named fonts; the SVG viewer resolves the same family.
//!
//! Label discovery happens before drawing. Typst returns exact advances and ink
//! bounds, keyed by text and font-size bits, and this module reconstructs a
//! measurement-backed font without loading files in WASM. Standalone SVG keeps
//! text as text; mechanism scenes transfer it to Typst through native layers.

use crate::Error;
use chitin_chemdraw::{
  Drawing, Primitive,
  font::{FontFace, TextMetrics, TextRequest},
  geometry::Point,
  scene::{Color, Polygon},
  svg,
};
use serde::{Deserialize, Serialize};

/// One exact label run requested from the measuring host.
#[derive(Debug, Serialize)]
pub struct Label {
  /// Literal label content.
  pub text: String,
  /// Font size in SVG drawing units.
  pub size: f64,
  /// Opaque exact size token; hosts return it unchanged across numeric codecs.
  pub key: String,
}

/// Host-measured advance and baseline-relative ink bounds, in SVG units.
#[derive(Debug, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct Measurement {
  /// Literal label content.
  pub text: String,
  /// Exact requested font size.
  pub size: f64,
  /// Exact request token. Absent accepts legacy numeric-only measurements.
  #[serde(default)]
  pub key: Option<String>,
  /// Horizontal advance.
  pub advance: f64,
  /// Minimum x and y in a y-down baseline coordinate frame.
  pub min: [f64; 2],
  /// Maximum x and y in the same frame.
  pub max: [f64; 2],
}

/// Reconstructs a host font from the label-discovery round trip.
///
/// # Parameters
/// - `family`: host font identity echoed by text layers and SVG family names.
/// - `rows`: exact metrics in y-down, baseline-relative drawing coordinates.
///
/// # Returns
/// A font backed only by supplied metrics. Missing runs fail when measured;
/// reconstruction does not invent fallback glyphs or query installed fonts.
///
/// # Errors
/// Rejects invalid size tokens, inconsistent numeric sizes and invalid metrics.
/// Rows without tokens use their numeric size for compatibility with older hosts.
pub(crate) fn face(family: &str, rows: &[Measurement]) -> Result<FontFace, Error> {
  let entries = rows
    .iter()
    .map(|row| {
      let size = match &row.key {
        Some(key) => {
          let bits = u64::from_str_radix(key, 16)
            .map_err(|_| Error::Input("invalid font measurement token".into()))?;
          let size = f64::from_bits(bits);
          // JSON codecs may round the display number slightly. The echoed token
          // is authoritative, but only within a few representable numeric steps.
          if key.len() != 16
            || !size.is_finite()
            || size <= 0.
            || !row.size.is_finite()
            || row.size <= 0.
            || size.to_bits().abs_diff(row.size.to_bits()) > 4
          {
            return Err(Error::Input(
              "font measurement token does not match its numeric size".into(),
            ));
          }
          size
        }
        None => row.size,
      };
      Ok((
        TextRequest::new(&row.text, size)?,
        TextMetrics {
          advance: row.advance,
          min: Point::new(row.min[0], row.min[1]),
          max: Point::new(row.max[0], row.max[1]),
        },
      ))
    })
    .collect::<Result<Vec<_>, Error>>()?;
  Ok(FontFace::from_measurements(family, entries)?)
}

/// Escapes literal text and font names for SVG text nodes and quoted attributes.
fn escape(value: &str) -> String {
  value
    .replace('&', "&amp;")
    .replace('<', "&lt;")
    .replace('>', "&gt;")
    .replace('"', "&quot;")
    .replace('\'', "&apos;")
}

/// Borrows the body of an SVG document generated by Chitin's exporter.
///
/// This helper expects a generated outer `<svg>` wrapper, not arbitrary XML.
/// Missing opening or closing delimiters are reported as input errors.
fn body(svg: &str) -> Result<&str, Error> {
  let start = svg
    .find('>')
    .ok_or_else(|| Error::Input("invalid SVG header".into()))?
    + 1;
  let end = svg
    .rfind("</svg>")
    .ok_or_else(|| Error::Input("invalid SVG closing tag".into()))?;
  Ok(&svg[start..end])
}

/// Exports a standalone molecular drawing with viewer-resolved host text.
///
/// # Parameters
/// - `drawing`: measured molecular primitives, with host text at the top level.
/// - `options`: standalone background and padding in drawing units.
/// - `family`: the same font family that supplied the drawing's measurements.
///
/// # Returns
/// SVG whose frame includes all ink and whose text uses measured target advances.
/// Geometry is exported in painter order without converting host text to outlines.
///
/// # Errors
/// Rejects empty drawings, invalid framing or geometry, and export failures.
/// Nested host text is not flattened here; composed mechanism groups use the
/// native layer encoder instead.
pub(crate) fn export(
  drawing: &Drawing,
  options: &svg::SvgOptions,
  family: &str,
) -> Result<String, Error> {
  let bounds = drawing
    .bounds()
    .ok_or_else(|| Error::Input("empty drawing".into()))?;
  // Let Chitin frame the exact measured envelope, including background/padding.
  let frame = Drawing::new(vec![Primitive::Polygon(Polygon {
    points: vec![
      bounds.min(),
      Point::new(bounds.max().x, bounds.min().y),
      bounds.max(),
      Point::new(bounds.min().x, bounds.max().y),
    ],
    color: Color {
      alpha: 0,
      ..Color::BLACK
    },
    source: None,
  })])
  .map_err(|error| Error::Input(error.to_string()))?;
  let mut output = svg::export(&frame, options)?;
  output.truncate(
    output
      .rfind("</svg>")
      .ok_or_else(|| Error::Input("invalid SVG framing".into()))?,
  );
  let geometry_options = svg::SvgOptions {
    padding: 0.,
    background: None,
  };
  // Keep the original painter order: collecting all text at the end would move
  // labels across later geometry or debug backgrounds and change compositing.
  for primitive in drawing.primitives() {
    match primitive {
      Primitive::Text(text) => {
        output.push_str(&format!(
          "<text x=\"{}\" y=\"{}\" font-family=\"{}\" font-size=\"{}\" font-weight=\"400\" font-style=\"normal\" style=\"font-kerning:none;font-variant-ligatures:none\" textLength=\"{}\" lengthAdjust=\"spacingAndGlyphs\" fill=\"#{:02x}{:02x}{:02x}\" fill-opacity=\"{}\">{}</text>\n",
          text.origin.x, text.origin.y, escape(family), text.font_size, text.width,
          text.color.red, text.color.green, text.color.blue, f64::from(text.color.alpha) / 255., escape(&text.content),
        ));
      }
      other => {
        let scene =
          Drawing::new(vec![other.clone()]).map_err(|error| Error::Input(error.to_string()))?;
        output.push_str(body(&svg::export(&scene, &geometry_options)?)?);
      }
    }
  }
  output.push_str("</svg>\n");
  Ok(output)
}
